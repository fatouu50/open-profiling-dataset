#!/usr/bin/env python3
"""Validate every profile in dataset/ against the schema AND the sourcing rules.

JSON Schema can express structure. It cannot express the rules that actually
protect this dataset from the failure mode documented in docs/roster-audit.md:

  * a claim asserting a value must carry at least one source
  * a claim marked 'unverified' must carry a null value and a note
  * a claim marked 'contested' must explain the disagreement
  * 'established' requires two or more independent sources
  * inadmissible source types (dramatisations, wikis, AI output) are rejected
  * a subject must be on the roster, and must not be in quarantine

Those are enforced here.

Usage:
    python3 scripts/validate.py            # validate everything
    python3 scripts/validate.py FILE...    # validate specific files

Exit code 0 = clean, 1 = errors found.
"""

from __future__ import annotations

import csv
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROFILE_SCHEMA = ROOT / "schema" / "profile.schema.json"
CASE_SCHEMA = ROOT / "schema" / "case.schema.json"
DATASET = ROOT / "dataset"
CASES = ROOT / "cases"
INDEX = ROOT / "index"

# Substrings that indicate a source is inadmissible under docs/sourcing-policy.md.
# Dramatisations are the specific vector that contaminated the inherited drafts:
# the Larry Hall profile tracked the television series, not the record.
INADMISSIBLE = [
    "wikipedia", "wikispooks", "fandom", "murderpedia", "morderpedia",
    "netflix", "hulu", "apple tv", "paramount+", "amazon prime",
    "dramatisation", "dramatization", "miniseries", "mini-series",
    "tv series", "television series", "docudrama", "biopic",
    "chatgpt", "gpt-4", "gpt-5", "claude", "gemini", "llm-generated",
    "generated by ai", "ai-generated",
    "reddit.com", "quora.com", "youtube.com/watch",
]

# Known dramatisations whose titles show up as if they were sources.
DRAMATISATION_TITLES = [
    "black bird", "mindhunter", "monster: the jeffrey dahmer story",
    "extremely wicked", "the serpent", "des ", "dahmer",
    "conversations with a killer",
]

VALID_CONFIDENCE = {"established", "reported", "contested", "unverified"}


class Problem:
    __slots__ = ("path", "where", "message", "severity")

    def __init__(self, path, where, message, severity="error"):
        self.path = path
        self.where = where
        self.message = message
        self.severity = severity

    def __str__(self):
        tag = "ERROR" if self.severity == "error" else "warn "
        return f"  [{tag}] {self.where}: {self.message}"


def load_index():
    roster, cases, quarantine = {}, {}, {}
    rp, cp, qp = INDEX / "roster.csv", INDEX / "cases.csv", INDEX / "quarantine.csv"
    if rp.exists():
        with open(rp, encoding="utf-8") as fh:
            for row in csv.DictReader(fh):
                roster[row["id"]] = row
    if cp.exists():
        with open(cp, encoding="utf-8") as fh:
            for row in csv.DictReader(fh):
                cases[row["id"]] = row
    if qp.exists():
        with open(qp, encoding="utf-8") as fh:
            for row in csv.DictReader(fh):
                quarantine[row["name_as_inherited"].lower()] = row
    return roster, cases, quarantine


def is_claim(node):
    return (
        isinstance(node, dict)
        and "confidence" in node
        and "sources" in node
        and "value" in node
    )


def check_source(src, where, problems, path):
    if not isinstance(src, dict):
        problems.append(Problem(path, where, "source is not an object"))
        return

    citation = str(src.get("citation", ""))
    url = str(src.get("url", ""))
    blob = f"{citation} {url}".lower()

    if len(citation.strip()) < 10:
        problems.append(Problem(path, where, "citation is empty or too short to identify a source"))

    tier = src.get("tier")
    if tier not in (1, 2, 3, 4):
        problems.append(Problem(path, where, f"tier must be 1-4, got {tier!r}"))

    for bad in INADMISSIBLE:
        if bad in blob:
            problems.append(Problem(
                path, where,
                f"inadmissible source: contains {bad!r}. "
                "Dramatisations, wikis and AI output are not sources at any tier. "
                "See docs/sourcing-policy.md."))
            break

    for title in DRAMATISATION_TITLES:
        if title in blob and "tier" in src and src.get("tier", 4) <= 3:
            problems.append(Problem(
                path, where,
                f"cites what appears to be a dramatisation ({title.strip()!r}) at tier {src.get('tier')}. "
                "A dramatisation is never a tier 1-3 source."))
            break

    # A tier 1 claim should look like a record, not a narrative.
    # Matches reporter citations (Bundy v. State, 471 So. 2d 9), docket numbers,
    # and the vocabulary of official documents.
    if tier == 1:
        looks_like_record = bool(re.search(
            r"(\sv\.\s"                      # case name: "X v. Y"
            r"|\bNo\.\s*\d"                  # docket number
            r"|\d\s+(?:F|So|U\.?S|N\.?[EW]|S\.?[EW]|P|A|Cal|Ill)\.?\s?\d?d?\s+\d"  # reporter cite
            r"|\bU\.?S\.?C\.?\b"             # statute
            r"|\bCir\.|\bCrim\.|\bFla\.|\bCal\.\s?(?:App|Ct)"
            r"|\bdocket\b|\btranscript\b|\bindictment\b|\bjudg[e]?ment\b"
            r"|\bopinion\b|\baffidavit\b|\bdeposition\b|\bwarrant\b"
            r"|\brecord\b|\breport\b|\bcommission\b|\bbureau\b|\bministry\b"
            r"|\bdepartment\b|\bcoroner\b|\binquest\b|\bnational (?:research|academies)\b"
            r"|\bcouncil\b|\bprogramme? documentation\b|\bcensus\b|\bstatistics\b"
            # Official statements by a prosecuting or investigating agency.
            # Authoritative for counts, dates and dispositions; see
            # docs/sourcing-policy.md on their limits as advocacy documents.
            r"|\bdistrict attorney\b|\battorney general\b|\bprosecutor\b"
            r"|\bnews release\b|\bpress release\b|\bsheriff\b|\bconstabulary\b"
            r"|\bprocureur\b|\bparquet\b|\bstaatsanwaltschaft\b)",
            citation, re.I))
        if not looks_like_record:
            problems.append(Problem(
                path, where,
                "declared tier 1 (primary record) but the citation does not look like "
                "a court filing, transcript or official report. Downgrade or re-cite.",
                severity="warn"))


def check_claim(node, where, problems, path):
    conf = node.get("confidence")
    sources = node.get("sources")
    value = node.get("value")
    notes = node.get("notes")

    if conf not in VALID_CONFIDENCE:
        problems.append(Problem(path, where, f"confidence must be one of {sorted(VALID_CONFIDENCE)}, got {conf!r}"))
        return

    if not isinstance(sources, list):
        problems.append(Problem(path, where, "sources must be an array"))
        return

    # --- the central rule -------------------------------------------------
    if conf == "unverified":
        if value is not None:
            problems.append(Problem(
                path, where,
                "confidence is 'unverified' but a value is asserted. "
                "An unverified claim must have value: null. This is the rule that "
                "prevents unsourced assertions entering the dataset."))
        if not notes or len(str(notes).strip()) < 10:
            problems.append(Problem(
                path, where,
                "'unverified' requires a note stating what was searched and not found."))
    else:
        if len(sources) == 0:
            problems.append(Problem(
                path, where,
                f"confidence is '{conf}' but no source is given. "
                "Either cite a source or set confidence to 'unverified' with value: null."))

    if conf == "established" and len(sources) < 2:
        problems.append(Problem(
            path, where,
            "'established' requires two or more independent sources. "
            "With one source, use 'reported'."))

    if conf == "established" and sources:
        tiers = [s.get("tier") for s in sources if isinstance(s, dict)]
        if not any(t in (1, 2) for t in tiers):
            problems.append(Problem(
                path, where,
                "'established' requires at least one tier 1 or tier 2 source.",
                severity="warn"))

    if conf == "contested" and (not notes or len(str(notes).strip()) < 10):
        problems.append(Problem(
            path, where,
            "'contested' requires a note describing what the sources disagree about."))

    for i, src in enumerate(sources):
        check_source(src, f"{where}.sources[{i}]", problems, path)


def walk(node, where, problems, path):
    if is_claim(node):
        check_claim(node, where, problems, path)
        return
    if isinstance(node, dict):
        for k, v in node.items():
            walk(v, f"{where}.{k}" if where else k, problems, path)
    elif isinstance(node, list):
        for i, v in enumerate(node):
            walk(v, f"{where}[{i}]", problems, path)


def check_document(doc, path, roster, cases, quarantine, problems):
    pid = doc.get("id")
    is_case = path.parent.name == "cases"

    if is_case:
        if cases and pid and pid not in cases:
            problems.append(Problem(path, "id", f"{pid!r} is not in index/cases.csv"))
        if pid and pid in roster:
            problems.append(Problem(
                path, "id",
                f"{pid!r} appears in BOTH index/roster.csv and index/cases.csv. "
                "A subject is either an offender profile or a case record, never both — "
                "otherwise it is counted twice in any aggregate."))
        # A case record must justify its own exclusion.
        rationale = doc.get("exclusion_rationale") or {}
        if doc.get("case_type") == "exonerated" and not rationale.get("not_an_exoneration") is False:
            pass  # exonerated records need no innocence warning
        if doc.get("record_status") == "complete" and not (doc.get("research_value") or {}).get("why_recorded"):
            problems.append(Problem(
                path, "research_value.why_recorded",
                "a case record marked 'complete' must state why it is in the dataset. "
                "A case record with no stated analytic use is an accusation with citations."))
    else:
        if roster and pid and pid not in roster:
            problems.append(Problem(path, "id", f"{pid!r} is not in index/roster.csv"))
        if pid and pid in cases:
            problems.append(Problem(
                path, "id",
                f"{pid!r} is registered in index/cases.csv. It cannot also be an offender profile."))

    name = ""
    ident = doc.get("identity") or {}
    ln = ident.get("legal_name")
    if isinstance(ln, dict):
        name = str(ln.get("value") or "")
    if name.lower() in quarantine:
        q = quarantine[name.lower()]
        problems.append(Problem(
            path, "identity.legal_name",
            f"{name!r} is quarantined ({q['category']}): {q['reason']}"))

    prov = doc.get("provenance") or {}
    if prov.get("ai_assisted") is None:
        problems.append(Problem(
            path, "provenance.ai_assisted",
            "must be declared true or false. Undisclosed AI drafting is how the "
            "inherited list acquired fabricated entries.", severity="warn"))

    # A completed record must state its own limits.
    if doc.get("record_status") == "complete":
        dq = doc.get("data_quality") or {}
        if not dq.get("known_gaps"):
            problems.append(Problem(
                path, "data_quality.known_gaps",
                "a record marked 'complete' must list what it does not establish."))

    # No behavioural profile without a conviction. (Case records carry no
    # behavioural section at all, so this applies to profiles.)
    status = ""
    js = ident.get("judicial_status")
    if isinstance(js, dict):
        status = str(js.get("value") or "").lower()
    if any(w in status for w in ("charged", "awaiting trial", "not convicted", "acquitted", "exonerated")):
        if doc.get("offence_behaviour"):
            problems.append(Problem(
                path, "offence_behaviour",
                f"judicial_status is {status!r}. No behavioural profile may be "
                "published for a subject who has not been convicted."))

    walk(doc, "", problems, path)


def main(argv):
    try:
        import jsonschema
    except ImportError:
        print("jsonschema is required:  pip install jsonschema --break-system-packages")
        return 2

    profile_validator = jsonschema.Draft202012Validator(
        json.loads(PROFILE_SCHEMA.read_text(encoding="utf-8")))
    case_validator = jsonschema.Draft202012Validator(
        json.loads(CASE_SCHEMA.read_text(encoding="utf-8")))
    roster, cases, quarantine = load_index()

    files = [pathlib.Path(a) for a in argv[1:]] or (
        sorted(DATASET.glob("*.json")) + sorted(CASES.glob("*.json")))
    if not files:
        print("No records found in dataset/ or cases/.")
        return 0

    total = 0
    for path in files:
        problems: list[Problem] = []
        try:
            doc = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            print(f"\n{path.name}\n  [ERROR] not valid JSON: {exc}")
            total += 1
            continue

        validator = case_validator if path.parent.name == "cases" else profile_validator
        for err in validator.iter_errors(doc):
            loc = ".".join(str(p) for p in err.absolute_path) or "<root>"
            problems.append(Problem(path, loc, f"schema: {err.message}"))

        check_document(doc, path, roster, cases, quarantine, problems)

        errors = [p for p in problems if p.severity == "error"]
        warns = [p for p in problems if p.severity == "warn"]
        total += len(errors)

        kind = "case" if path.parent.name == "cases" else "profile"
        if problems:
            print(f"\n{path.name} ({kind})  —  {len(errors)} error(s), {len(warns)} warning(s)")
            for p in problems:
                print(p)
        else:
            print(f"\n{path.name} ({kind})  —  clean")

    print(f"\n{'=' * 60}")
    if total:
        print(f"FAILED: {total} error(s) across {len(files)} file(s).")
        return 1
    print(f"PASSED: {len(files)} file(s) validated.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
